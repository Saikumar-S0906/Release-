def write_locale(loc: str, data: dict[str, str]) -> None:
    missing = [k for k in EN if k not in data]
    extras = [k for k in data if k not in EN]
    if missing:
        raise SystemExit(f"{loc}: missing {len(missing)} e.g. {missing[:5]}")
    if extras:
        raise SystemExit(f"{loc}: extras {extras[:5]}")
    # force app_name
    data["app_name"] = "PixiJoy"
    ordered = {k: data[k] for k in EN}
    path = CACHE / f"{loc}.json"
    path.write_text(json.dumps(ordered, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({len(ordered)})")


